using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using System.Windows.Media;

namespace BloodBankAccounting.Views;

public partial class BloodInventoryView : UserControl
{
    public BloodInventoryView()
    {
        InitializeComponent();
    }

    // ??????????????????????????????????????????????????????????????
    // Outer ScrollViewer:
    //   - Scroll ???? ????
    //   - Shift + Wheel ? Scroll ????
    // ??????????????????????????????????????????????????????????????
    private void OuterScroll_PreviewMouseWheel(object sender, MouseWheelEventArgs e)
    {
        if (Keyboard.Modifiers != ModifierKeys.Shift) return;

        var sv = (ScrollViewer)sender;
        sv.ScrollToHorizontalOffset(sv.HorizontalOffset - e.Delta / 3.0);
        e.Handled = true;
    }

    // ??????????????????????????????????????????????????????????????
    // Inner ScrollViewers (????? ??????? + ????? ????????):
    //   - ??? ??? ??? Scroll ???? ?????? ?? ?????? ?
    //     ???? ???????? ??????? ????? ????? ????? ??? ??? Parent
    //     ??? ????? ??? Scroll ?? ??? Outer ScrollViewer ??????
    // ??????????????????????????????????????????????????????????????
    private void InnerScroll_PreviewMouseWheel(object sender, MouseWheelEventArgs e)
    {
        var sv = (ScrollViewer)sender;

        bool scrollingUp = e.Delta > 0;
        bool scrollingDown = e.Delta < 0;
        bool atTop = sv.VerticalOffset == 0;
        bool atBottom = sv.VerticalOffset >= sv.ScrollableHeight;

        // ??? ??? ??? Inner Scroll ??? ??? ??? ?????? ??????? ????
        bool shouldBubble = (scrollingUp && atTop) || (scrollingDown && atBottom);

        if (!shouldBubble) return;

        // ???? ???????? ???????
        e.Handled = true;

        // ???? ????? ????? ??? ??? Parent ??? Outer ScrollViewer ???????
        var bubbleArgs = new MouseWheelEventArgs(e.MouseDevice, e.Timestamp, e.Delta)
        {
            RoutedEvent = MouseWheelEvent,
            Source = e.Source
        };
        (sv.Parent as UIElement)?.RaiseEvent(bubbleArgs);
    }
}